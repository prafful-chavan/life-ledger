#!/usr/bin/env node
/**
 * Runs the tax audit over a private cases file and writes a Markdown report next to it.
 *   node tools/tax/run-audit.js ~/Desktop/Tax_docs/00_Analysis/data/cases.json [--plan plan.json]
 * The cases file and the report stay outside the repository (they hold personal figures).
 */
const fs = require("fs");
const path = require("path");
const E = require("./engine");
const { audit } = require("./audit");
const { plan } = require("./planner");

const inr = (v) => (v < 0 ? "−" : "") + "₹" + Math.abs(Math.round(Number(v) || 0)).toLocaleString("en-IN");

function unfiledCheck(u) {
  const t = E.computeTax({ fy: u.fy, regime: u.regime || "old", grossSalary: u.grossSalary, exemptAllowances: u.exemptAllowances, deductions: u.deductions, otherIncome: u.otherIncome, gains: u.gains });
  return { ...u, tax: t.totalTax, shortfall: t.totalTax - (Number(u.tds) || 0), totalIncome: t.totalIncome };
}

function render(results, unfiled, plans) {
  const out = [`# Tax audit — ${new Date().toISOString().slice(0, 10)}`, "", "Generated by Life Ledger `tools/tax/run-audit.js` from the cases file. Planning aid only; a CA confirms.", ""];
  out.push("| Person | FY (AY) | Form | Regime | Tax filed | Tax on documented figures | Extra tax | Refund claimed → on documents | High-severity items |", "|---|---|---|---|---|---|---|---|---|");
  for (const r of results) out.push(`| ${r.person} | ${r.fy} (${r.ay}) | ${r.form} | ${r.regime} | ${inr(r.filedTax)} | ${inr(r.correctedTax)} | ${inr(r.extraTaxIfCorrected)} | ${inr(r.refundClaimed)} → ${inr(r.refundOnDocumentedFigures)} | ${r.findings.filter((f) => f.severity === "high").length} |`);
  for (const u of unfiled) out.push(`| ${u.person} | ${u.fy} (${E.ayOf(u.fy)}) | not filed | ${u.regime} | — | ${inr(u.tax)} | ${inr(u.shortfall)} unpaid | — | ${u.shortfall > 0 ? 1 : 0} |`);
  for (const r of results) {
    out.push("", `## ${r.person} — FY ${r.fy} (AY ${r.ay}), ${r.form}, ${r.regime} regime`);
    if (!r.findings.length) { out.push("No issues found."); continue; }
    for (const f of r.findings) out.push(`- **[${f.severity.toUpperCase()}] ${f.title}**${f.taxImpact ? ` (tax effect ${inr(f.taxImpact)})` : ""}: ${f.detail}${f.fix ? ` *Fix:* ${f.fix}` : ""}`);
  }
  for (const p of plans) {
    out.push("", `## Plan — ${p.person}, FY ${p.fy}${p.assumedRules ? " (rules assumed same as FY 2025-26)" : ""}`);
    out.push(`- Regime: **${p.better}** (old ${inr(p.regimes.old.tax)} vs new ${inr(p.regimes.new?.tax)}; saves ${inr(p.saving)}). Marginal rate ${p.marginalRatePct}% + cess.`);
    out.push(`- Projected TDS ${inr(p.tdsProjected)} → ${p.balance >= 0 ? `refund about ${inr(p.balance)}` : `pay about ${inr(-p.balance)} more`}. File **${p.form}**.`);
    out.push("- Levers, biggest first:", ...p.levers.map((l) => `  - ${l.title}: about ${inr(l.yearlySaving)} a year. ${l.detail}`));
    if (p.missedAdvance && p.nextAdvance) out.push(`- **Advance tax:** earlier instalments are past (small 234C interest). Pay ${inr(p.nextAdvance.cumulativeAmount)} in total by ${p.nextAdvance.date}.`);
    out.push("- Calendar:", ...p.calendar.map((c) => `  - ${c.date}: ${c.what}${c.status === "past" ? " *(past)*" : ""}`));
  }
  return out.join("\n") + "\n";
}

if (require.main === module) {
  const file = process.argv[2];
  if (!file) { console.error("usage: run-audit.js <cases.json> [--plan <plan.json>]"); process.exit(2); }
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const results = (data.cases || []).map(audit);
  const unfiled = (data.unfiled || []).map(unfiledCheck);
  const planIdx = process.argv.indexOf("--plan");
  const plans = planIdx > 0 ? JSON.parse(fs.readFileSync(process.argv[planIdx + 1], "utf8")).map((x) => plan(x)) : [];
  const outFile = path.join(path.dirname(path.resolve(file)), "..", `TAX-AUDIT-${new Date().toISOString().slice(0, 10)}.md`);
  fs.writeFileSync(outFile, render(results, unfiled, plans));
  fs.writeFileSync(path.join(path.dirname(path.resolve(file)), "audit-results.json"), JSON.stringify({ results, unfiled, plans }, null, 1));
  console.log(`wrote ${outFile}`);
  for (const r of results) console.log(`${r.person} ${r.fy}: filed ${r.filedTax} corrected ${r.correctedTax} (+${r.extraTaxIfCorrected}); ${r.findings.map((f) => f.id).join(", ")}`);
  for (const u of unfiled) console.log(`${u.person} ${u.fy} unfiled: tax ${u.tax}, unpaid ${u.shortfall}`);
}

module.exports = { render, unfiledCheck };
